from __future__ import annotations

import streamlit as st

from pdf_analyzer import explain_summary, extract_pdf_pages, summarize_pages


st.set_page_config(page_title="PDF Summary & Explainer", page_icon="📄")
st.title("PDF Summary & Explainer")
st.write("Upload a PDF to get a concise summary and a plain-language overview.")
st.caption(
    "Your PDF is processed locally in this app. Scanned pages use OCR, which "
    "requires the Microsoft Visual C++ 2015-2022 Redistributable on Windows."
)

uploaded_pdf = st.file_uploader("Choose a PDF", type=["pdf"])
summary_length = st.select_slider(
    "Summary length",
    options=["Brief", "Standard", "Detailed"],
    value="Standard",
)
sentence_counts = {"Brief": 3, "Standard": 6, "Detailed": 10}

if uploaded_pdf is not None:
    if st.button("Summarize and explain PDF", type="primary"):
        try:
            pages = extract_pdf_pages(uploaded_pdf.getvalue())
        except ValueError as error:
            st.error(str(error))
        except RuntimeError as error:
            st.error(str(error))
        except Exception as error:
            st.error(f"Could not read this PDF: {error}")
        else:
            summary = summarize_pages(pages, sentence_counts[summary_length])
            st.success(f"Read {len(pages)} page(s).")
            if not summary:
                st.warning(
                    "Text was extracted, but it did not contain enough complete "
                    "sentences to make a useful summary."
                )
            else:
                st.subheader("Summary")
                for page_number, sentence in summary:
                    st.markdown(f"- {sentence} *(Page {page_number})*")

                st.subheader("Plain-language explanation")
                st.markdown(explain_summary(summary))
                st.caption(
                    "This explanation is assembled from the PDF's own sentences "
                    "rather than generated by a large language model."
                )
